export const requestsMessages = Object.fromEntries(['en', 'fr', 'ja'].map((locale, i) => [
  locale, Object.fromEntries(rows.map((row) => [row[0], row[i]])),
]));

export function createRequestsLocale(locale = 'en') {
  const shared = createLocale(locale);
  const dictionary = requestsMessages[shared.locale];
  return {
    ...shared,
    t: (key, values = {}) => Object.hasOwn(dictionary, key)
      ? dictionary[key].replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match)
      : shared.t(key, values),
  };
}

/** Translate display fields only; classifier keys, order, thresholds and IDs stay canonical. */
export function localizeRequestsManifest(manifest, { t }) {
  const display = (item) => Object.fromEntries(Object.entries(item).map(([key, value]) => [
    key, ['label', 'short', 'description', 'long', 'name'].includes(key) && typeof value === 'string' ? t(value) : value,
  ]));
  const presets = manifest.presets.some((preset) => preset.id === 'all') ? manifest.presets : [{
    id: 'all', label: 'All topics',
    description: 'Browse every topic, including bugs, questions and other discussions', params: 'scope=all',
  }, ...manifest.presets];
  return {
    ...manifest,
    questions: manifest.questions.map((question) => {
      const result = display(question);
      for (const key of ['levels', 'bands', 'choices']) if (question[key]) result[key] = question[key].map(display);
      return result;
    }),
    categories: manifest.categories.map(display),
    languages: manifest.languages.map(display),
    presets: presets.map(display),
  };
}
